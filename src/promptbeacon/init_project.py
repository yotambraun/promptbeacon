"""``promptbeacon init``: set a repository up for weekly AI-visibility checks.

Reads the project from the working tree (``pyproject.toml``, ``package.json``,
``Cargo.toml``, ``README``, the git remote), proposes a category with its
basis, and plans the files to write: a weekly GitHub workflow that uses the
project's own Action (``yotambraun/promptbeacon@v1``) and, on request, a
pinned scan protocol. Nothing here writes files or touches the network; the
CLI shows the plan, asks, and then calls :func:`write_plan`.
"""

from __future__ import annotations

import configparser
import difflib
import json
import re
import sys
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

from promptbeacon.core.config import API_KEY_ENV_VARS, Provider, parse_model_overrides
from promptbeacon.projects.infer import CategoryGuess, guess_category, guess_competitors
from promptbeacon.projects.sources import ProjectMetadata

if sys.version_info >= (3, 11):
    import tomllib
else:  # pragma: no cover - exercised on Python 3.10 only
    import tomli as tomllib

ACTION = "yotambraun/promptbeacon@v1"
WORKFLOW_PATH = ".github/workflows/ai-visibility.yml"
PROTOCOL_PATH = ".promptbeacon/protocol.json"
OUTPUT_DIR = ".promptbeacon"
GENERATED_MARKER = "# Generated by `promptbeacon init`."
README_NAMES = ("README.md", "README.rst", "README.txt", "README")
DEFAULT_MAX_COST = 0.05
PROMPTBEACON_URL = "https://github.com/yotambraun/promptbeacon"

FileStatus = Literal["create", "update", "unchanged"]


# --- detection ------------------------------------------------------------------


@dataclass
class LocalProject:
    """What the working tree says about the project."""

    root: Path
    name: str | None = None
    description: str = ""
    keywords: list[str] = field(default_factory=list)
    language: str | None = None
    github: str | None = None  # owner/name
    branch: str = "main"
    readme: str = ""
    found: list[str] = field(default_factory=list)  # files the facts came from
    protocol: dict[str, Any] | None = None  # an existing .promptbeacon/protocol.json

    def metadata(self) -> ProjectMetadata:
        """The same metadata shape the registry sources produce."""
        source = self.found[0] if self.found else "local"
        return ProjectMetadata(
            source=source,
            ref=self.github or self.name or self.root.name,
            name=self.name or self.root.name,
            description=self.description,
            keywords=list(self.keywords),
            language=self.language,
            url=f"https://github.com/{self.github}" if self.github else None,
            readme=self.readme,
        )


def _read_toml(path: Path) -> dict[str, Any]:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _read_json(path: Path) -> dict[str, Any]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return data if isinstance(data, dict) else {}


_GITHUB_URL = re.compile(
    r"github\.com[:/]+(?P<owner>[\w.-]+)/(?P<name>[\w.-]+?)(?:\.git)?/?(?:[#?].*)?$"
)


def github_ref_from_url(url: str | None) -> str | None:
    """``owner/name`` from a GitHub https or ssh URL, else ``None``."""
    if not url:
        return None
    m = _GITHUB_URL.search(url.strip())
    return f"{m.group('owner')}/{m.group('name')}" if m else None


def _git_dir(root: Path) -> Path | None:
    git = root / ".git"
    if git.is_dir():
        return git
    if git.is_file():  # worktrees and submodules: "gitdir: <path>"
        text = git.read_text(encoding="utf-8", errors="replace").strip()
        if text.startswith("gitdir:"):
            path = Path(text.split(":", 1)[1].strip())
            return path if path.is_absolute() else (root / path).resolve()
    return None


def read_git(root: Path) -> tuple[str | None, str | None]:
    """``(github owner/name, default branch)`` from ``.git``, without running git."""
    git = _git_dir(root)
    if git is None:
        return None, None
    parser = configparser.ConfigParser(strict=False, interpolation=None)
    try:
        parser.read(git / "config", encoding="utf-8")
    except (configparser.Error, OSError):
        return None, None
    url = None
    if parser.has_section('remote "origin"'):
        url = parser.get('remote "origin"', "url", fallback=None)
    else:
        for section in parser.sections():
            if section.startswith("remote ") and parser.has_option(section, "url"):
                url = parser.get(section, "url")
                break
    branch = None
    for head in (git / "refs" / "remotes" / "origin" / "HEAD", git / "HEAD"):
        try:
            text = head.read_text(encoding="utf-8").strip()
        except OSError:
            continue
        if text.startswith("ref:"):
            branch = (
                text.rsplit("/", 1)[-1]
                if "remotes/origin/" in text
                else (text.split("refs/heads/", 1)[-1])
            )
            break
    return github_ref_from_url(url), branch


def detect_project(root: Path) -> LocalProject:
    """Read the project's own files (first match wins for name and description)."""
    project = LocalProject(root=root)

    pyproject = root / "pyproject.toml"
    if pyproject.exists():
        data = _read_toml(pyproject)
        meta = data.get("project") or data.get("tool", {}).get("poetry") or {}
        if meta.get("name"):
            project.name = str(meta["name"])
            project.description = str(meta.get("description") or "")
            project.keywords = [str(k) for k in meta.get("keywords") or []]
            project.keywords += [
                str(c).split("::")[-1].strip()
                for c in meta.get("classifiers") or []
                if str(c).startswith("Topic ::")
            ]
            project.language = "Python"
            urls = meta.get("urls") or {}
            for value in [*urls.values(), meta.get("repository"), meta.get("homepage")]:
                project.github = project.github or github_ref_from_url(
                    str(value) if value else None
                )
            project.found.append("pyproject.toml")

    package = root / "package.json"
    if package.exists():
        data = _read_json(package)
        if data.get("name"):
            repo = data.get("repository")
            repo_url = repo.get("url") if isinstance(repo, dict) else repo
            if project.name is None:
                name = str(data["name"])
                project.name = name.split("/")[-1] if name.startswith("@") else name
                project.description = str(data.get("description") or "")
                project.keywords = [
                    str(k) for k in data.get("keywords") or [] if isinstance(k, str)
                ]
                dev = {
                    **data.get("devDependencies", {}),
                    **data.get("dependencies", {}),
                }
                project.language = (
                    "TypeScript"
                    if data.get("types") or data.get("typings") or "typescript" in dev
                    else "JavaScript"
                )
            project.github = project.github or github_ref_from_url(
                str(repo_url) if repo_url else None
            )
            project.found.append("package.json")

    cargo = root / "Cargo.toml"
    if cargo.exists():
        data = _read_toml(cargo).get("package") or {}
        if data.get("name"):
            if project.name is None:
                project.name = str(data["name"])
                project.description = str(data.get("description") or "")
                project.keywords = [str(k) for k in data.get("keywords") or []]
                project.keywords += [
                    str(c).split("::")[-1] for c in data.get("categories") or []
                ]
                project.language = "Rust"
            project.github = project.github or github_ref_from_url(
                str(data.get("repository") or "")
            )
            project.found.append("Cargo.toml")

    remote, branch = read_git(root)
    if remote:
        project.github = remote
        project.found.append("git remote")
    if branch:
        project.branch = branch
    if project.name is None and project.github:
        project.name = project.github.split("/")[-1]

    for name in README_NAMES:
        path = root / name
        if path.exists():
            try:
                project.readme = path.read_text(encoding="utf-8", errors="replace")[
                    :20_000
                ]
            except OSError:
                continue
            break

    protocol = root / PROTOCOL_PATH
    if protocol.exists():
        data = _read_json(protocol)
        if data.get("brand"):
            project.protocol = data
            project.found.append(PROTOCOL_PATH)
    return project


# --- plan -----------------------------------------------------------------------


@dataclass
class PlannedFile:
    """A file init wants to write, and how it compares with what is there."""

    path: str  # relative to the project root, with forward slashes
    content: str
    status: FileStatus
    existing: str | None = None
    generated_before: bool = False  # the existing file came from init

    def diff(self) -> str:
        """Unified diff from the existing file (empty when unchanged or new)."""
        if self.existing is None or self.status == "unchanged":
            return ""
        return "".join(
            difflib.unified_diff(
                self.existing.splitlines(keepends=True),
                self.content.splitlines(keepends=True),
                fromfile=f"{self.path} (current)",
                tofile=f"{self.path} (proposed)",
            )
        )


@dataclass
class InitPlan:
    """Everything ``promptbeacon init`` proposes, before anything is written."""

    project: LocalProject
    brand: str
    category: str | None
    category_basis: str
    category_confidence: str
    competitors: list[str]
    competitor_basis: str
    providers: list[Provider]
    models: dict[Provider, str]
    max_cost: float
    estimate_usd: float | None
    secrets: list[str]
    files: list[PlannedFile]
    badge_markdown: str
    badge_svg_markdown: str
    rank_badge_markdown: str | None
    uses_protocol: bool
    providers_explicit: bool = False

    def as_dict(self) -> dict[str, Any]:
        return {
            "project": {
                "root": str(self.project.root),
                "name": self.project.name,
                "description": self.project.description,
                "language": self.project.language,
                "github": self.project.github,
                "branch": self.project.branch,
                "read_from": self.project.found,
            },
            "brand": self.brand,
            "category": self.category,
            "category_basis": self.category_basis,
            "category_confidence": self.category_confidence,
            "competitors": self.competitors,
            "competitor_basis": self.competitor_basis,
            "providers": [p.value for p in self.providers],
            "models": {p.value: m for p, m in self.models.items()},
            "max_cost_usd": self.max_cost,
            "estimated_cost_per_run_usd": self.estimate_usd,
            "secrets": self.secrets,
            "files": [
                {
                    "path": f.path,
                    "status": f.status,
                    "generated_before": f.generated_before,
                    "content": f.content,
                    "diff": f.diff(),
                }
                for f in self.files
            ],
            "readme_badge": self.badge_markdown,
            "readme_badge_svg": self.badge_svg_markdown,
            "readme_rank_badge": self.rank_badge_markdown,
            "next_steps": next_steps(self),
        }


def guess_project_category(project: LocalProject) -> CategoryGuess:
    """The offline category guess for a local project (with its basis)."""
    guess = guess_category(project.metadata())
    if guess.category and project.found:
        guess.basis = f"{project.found[0]} {guess.basis}"
    return guess


def secrets_for(providers: Sequence[Provider]) -> list[str]:
    """Repository secrets the workflow needs (one key per hosted provider)."""
    names: list[str] = []
    for provider in providers:
        for name in API_KEY_ENV_VARS.get(provider, ())[:1]:
            if name not in names:
                names.append(name)
    return names


def _yaml_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)  # a JSON string is valid YAML


def round_up_cap(estimate: float) -> float:
    """A max-cost with headroom: twice the estimate, in steps of $0.05."""
    if estimate <= 0:
        return DEFAULT_MAX_COST
    steps = int((estimate * 2) / 0.05 + 0.999999)
    return round(max(1, steps) * 0.05, 2)


def render_workflow(plan: InitPlan) -> str:
    """The weekly workflow YAML (deterministic, so re-runs are idempotent)."""
    lines = [
        GENERATED_MARKER + " Safe to edit: running init again shows a diff",
        "# and asks before changing this file.",
        "#",
        f"# Weekly check of whether AI assistants recommend {plan.brand}. It refreshes a",
        f"# README badge, a share card and a score trend in {OUTPUT_DIR}/ and commits",
        "# them. Each run is billed to the API key(s) below and capped by max-cost.",
    ]
    if plan.secrets:
        lines.append("# Add the key(s) as repository secrets first, for example:")
        lines += [f"#   gh secret set {name}" for name in plan.secrets]
    lines += [
        "",
        "name: AI visibility",
        "",
        "on:",
        "  schedule:",
        '    - cron: "17 6 * * 1" # Mondays 06:17 UTC',
        "  workflow_dispatch:",
        "",
        "permissions:",
        "  contents: write # commit the refreshed badge, card and trend",
        "",
        "concurrency:",
        "  group: ai-visibility",
        "  cancel-in-progress: false",
        "",
        "jobs:",
        "  scan:",
        "    runs-on: ubuntu-latest",
        "    steps:",
        "      - uses: actions/checkout@v7",
        "",
        "      - name: Measure AI visibility",
        "        id: beacon",
        f"        uses: {ACTION}",
        "        with:",
    ]
    w = "          "
    if plan.uses_protocol:
        lines.append(f"{w}protocol: {PROTOCOL_PATH}")
        lines.append(f"{w}brand: {_yaml_str(plan.brand)}")
    else:
        lines.append(f"{w}brand: {_yaml_str(plan.brand)}")
        if plan.category:
            lines.append(f"{w}category: {_yaml_str(plan.category)}")
        if plan.competitors:
            lines.append(f"{w}competitors: |")
            lines += [f"{w}  {c}" for c in plan.competitors]
        if plan.providers_explicit:
            lines.append(
                f"{w}providers: {_yaml_str(' '.join(p.value for p in plan.providers))}"
            )
        if plan.models:
            lines.append(f"{w}models: |")
            lines += [f"{w}  {p.value}={m}" for p, m in plan.models.items()]
        else:
            lines += [
                f"{w}# Pin the model so the trend does not move when PromptBeacon's",
                f"{w}# defaults change (one provider=model_id per line; each provider",
                f"{w}# needs its key below):",
                f"{w}# models: |",
                f"{w}#   openai=gpt-6-luna",
                f"{w}#   anthropic=claude-haiku-5-5",
            ]
    estimate = (
        f" # estimated ${plan.estimate_usd:.4f} per run"
        if plan.estimate_usd is not None
        else ""
    )
    lines.append(f'{w}max-cost: "{plan.max_cost:.2f}"{estimate}')
    lines += [
        f"{w}badge-path: {OUTPUT_DIR}/badge.svg",
        f"{w}badge-endpoint-path: {OUTPUT_DIR}/badge.json",
    ]
    if len(plan.competitors) >= 2:
        lines.append(f"{w}rank-badge-path: {OUTPUT_DIR}/rank.svg")
    lines += [
        f"{w}card-path: {OUTPUT_DIR}/card.svg",
        f"{w}trend-path: {OUTPUT_DIR}/trend.json",
    ]
    if plan.secrets:
        lines.append("        env:")
        lines += [f"          {s}: ${{{{ secrets.{s} }}}}" for s in plan.secrets]
    lines += [
        "",
        "      - name: Commit badge, card and trend",
        "        run: |",
        '          git config user.name "github-actions[bot]"',
        '          git config user.email "41898282+github-actions[bot]@users.noreply.github.com"',
        f"          git add {OUTPUT_DIR}",
        "          if git diff --cached --quiet; then",
        '            echo "No change."',
        "          else",
        '            git commit -m "chore: refresh AI visibility badge (score '
        '${{ steps.beacon.outputs.score }})"',
        "            git push",
        "          fi",
    ]
    return "\n".join(lines) + "\n"


def render_protocol(plan: InitPlan, prompts: list[str]) -> str:
    """A pinned protocol: the same prompts, providers and models every run."""
    data: dict[str, Any] = {
        "brand": plan.brand,
        "competitors": plan.competitors,
        "providers": [p.value for p in plan.providers],
        "models": {p.value: m for p, m in plan.models.items()},
        "categories": [plan.category] if plan.category else [],
        "prompts": prompts,
        "runs": 0,
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _planned(root: Path, rel: str, content: str) -> PlannedFile:
    path = root / rel
    if not path.exists():
        return PlannedFile(rel, content, "create")
    existing = path.read_text(encoding="utf-8", errors="replace")
    status: FileStatus = "unchanged" if existing == content else "update"
    return PlannedFile(
        rel, content, status, existing, generated_before=GENERATED_MARKER in existing
    )


def badge_snippets(
    project: LocalProject, with_rank: bool
) -> tuple[str, str, str | None]:
    """README Markdown: shields endpoint badge, committed-SVG badge, rank badge."""
    from urllib.parse import quote

    svg = f"[![AI visibility]({OUTPUT_DIR}/badge.svg)]({PROMPTBEACON_URL})"
    rank_svg = f"[![AI rank]({OUTPUT_DIR}/rank.svg)]({PROMPTBEACON_URL})"
    if not project.github:
        return svg, svg, rank_svg if with_rank else None
    raw = (
        f"https://raw.githubusercontent.com/{project.github}/{project.branch}/"
        f"{OUTPUT_DIR}/"
    )
    shields = "https://img.shields.io/endpoint?url="
    badge = f"[![AI visibility]({shields}{quote(raw + 'badge.json', safe='')})]({PROMPTBEACON_URL})"
    rank = f"[![AI rank]({shields}{quote(raw + 'rank.json', safe='')})]({PROMPTBEACON_URL})"
    return badge, svg, rank if with_rank else None


def build_plan(
    project: LocalProject,
    *,
    brand: str | None = None,
    category: str | None = None,
    competitors: Sequence[str] | None = None,
    providers: Sequence[str] | None = None,
    models: Sequence[str] | None = None,
    max_cost: float | None = None,
    protocol: bool = False,
    workflow_path: str = WORKFLOW_PATH,
) -> InitPlan:
    """Plan the files for a project (flags win over everything detected).

    Raises:
        ValueError: Without a project name, or for an invalid provider/model.
    """
    from promptbeacon.builder import configure_beacon, parse_providers

    existing = project.protocol or {}
    brand = brand or existing.get("brand") or project.name
    if not brand:
        raise ValueError(
            "Could not find the project name (no pyproject.toml, package.json, "
            "Cargo.toml or git remote here). Pass --brand NAME, or run init in the "
            "project's root directory."
        )

    guess = guess_project_category(project)
    if category:
        basis, confidence = "--category", "high"
    elif existing.get("categories"):
        category = str(existing["categories"][0])
        basis, confidence = PROTOCOL_PATH, "high"
    else:
        category = guess.category
        basis, confidence = guess.basis, guess.confidence

    if competitors:
        comp_list = [c for c in competitors if c.strip()]
        comp_basis = "--competitor"
    elif existing.get("competitors"):
        comp_list = [str(c) for c in existing["competitors"]]
        comp_basis = PROTOCOL_PATH
    else:
        comp_list = guess_competitors(project.metadata())
        comp_basis = "README mentions" if comp_list else ""

    model_map = parse_model_overrides(list(models or []))
    if not model_map and existing.get("models"):
        model_map = parse_model_overrides(dict(existing["models"]))
    if providers:
        provider_list = parse_providers(list(providers))
    elif existing.get("providers"):
        provider_list = parse_providers(list(existing["providers"]))
    else:
        provider_list = list(model_map) or [Provider.OPENAI]

    beacon = configure_beacon(
        brand,
        competitors=comp_list,
        providers=[p.value for p in provider_list],
        models={p.value: m for p, m in model_map.items()},
        categories=[category] if category else None,
    )
    # Developer-oriented prompts, as for project scans (--repo, --pypi, ...).
    beacon = beacon.with_industry("developer-tools")
    if category:
        beacon = beacon.with_categories(category)
    estimate = beacon.estimate_cost()
    estimate_usd = round(estimate.total_usd, 6) if estimate.lines else None
    cap = max_cost if max_cost is not None else round_up_cap(estimate.total_usd)

    uses_protocol = protocol or project.protocol is not None
    plan = InitPlan(
        project=project,
        brand=brand,
        category=category,
        category_basis=basis,
        category_confidence=confidence,
        competitors=comp_list,
        competitor_basis=comp_basis,
        providers=provider_list,
        models=model_map,
        max_cost=cap,
        estimate_usd=estimate_usd,
        secrets=secrets_for(provider_list),
        files=[],
        badge_markdown="",
        badge_svg_markdown="",
        rank_badge_markdown=None,
        uses_protocol=uses_protocol,
        providers_explicit=bool(providers),
    )
    if project.protocol is not None:
        text = (project.root / PROTOCOL_PATH).read_text(encoding="utf-8")
        plan.files.append(PlannedFile(PROTOCOL_PATH, text, "unchanged", text))
    elif protocol:
        # Templates keep "{category}", so reports still record the category
        # (needed for the card title and the rank badge).
        prompts = beacon._get_templates() if category else []
        if not model_map:
            # Pin today's resolved models so the protocol stays comparable.
            plan.models = dict(beacon._models_to_query(requested=True))
        plan.files.append(
            _planned(project.root, PROTOCOL_PATH, render_protocol(plan, prompts))
        )
    plan.files.insert(0, _planned(project.root, workflow_path, render_workflow(plan)))
    plan.badge_markdown, plan.badge_svg_markdown, plan.rank_badge_markdown = (
        badge_snippets(project, len(comp_list) >= 2)
    )
    return plan


def write_plan(plan: InitPlan, paths: Sequence[str]) -> list[Path]:
    """Write the named planned files (the caller decides which, after asking)."""
    written = []
    for planned in plan.files:
        if planned.path not in paths or planned.status == "unchanged":
            continue
        target = plan.project.root / planned.path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(planned.content, encoding="utf-8")
        written.append(target)
    return written


def next_steps(plan: InitPlan) -> list[str]:
    """The short list printed at the end of ``promptbeacon init``."""
    steps = []
    repo = plan.project.github
    for name in plan.secrets:
        where = (
            f" (or https://github.com/{repo}/settings/secrets/actions)" if repo else ""
        )
        steps.append(
            f"Add the API key as a repository secret: gh secret set {name}{where}"
        )
    workflow = plan.files[0].path if plan.files else WORKFLOW_PATH
    paths = " ".join(f.path for f in plan.files)
    steps.append(
        f'Commit and push: git add {paths} && git commit -m "ci: weekly AI '
        'visibility check" && git push'
    )
    steps.append(
        f"Run it once now: gh workflow run {Path(workflow).name} (then weekly, "
        "on Mondays)"
    )
    steps.append("Add the badge to your README (snippet above)")
    local = f'promptbeacon scan "{plan.brand}"'
    if plan.category:
        local += f' -t "{plan.category}"'
    for c in plan.competitors[:3]:
        local += f' -c "{c}"' if " " in c else f" -c {c}"
    steps.append(f"Try a real scan locally first: {local} --estimate")
    return steps
